def main():
    doc = new_document()
    build_front_matter(doc)

    chapters = [
        ("CHAPTER 1", "INTRODUCTION", CH1_INTRODUCTION, None),
        ("CHAPTER 2", "SYSTEM ANALYSIS", None, "chapter2.txt"),
        ("CHAPTER 3", "SYSTEM DESIGN AND IMPLEMENTATION", None, ["chapter3_design.txt", "chapter3_impl.txt"]),
        ("CHAPTER 4", "SYSTEM TESTING", None, "chapter4.txt"),
        ("CHAPTER 5", "CONCLUSION AND FUTURE WORK", CH5_CONCLUSION, None),
        ("CHAPTER 6", "USER INTERFACE", None, "chapter6.txt"),
    ]

    for idx, (label, title, owned_text, draft_file) in enumerate(chapters):
        restart = 1 if idx == 0 else None
        start_new_section(doc, header_text="IARS \u00b7 %s" % label.title(),
                           footer_page_fmt="decimal", restart_at=restart)
        add_chapter_title(doc, label, title)
        if owned_text is not None:
            render_chapter_markdown(doc, owned_text, FIGURE_MAP)
        else:
            if isinstance(draft_file, list):
                combined = "\n\n".join(load_draft(f) for f in draft_file)
            else:
                combined = load_draft(draft_file)
            if label == "CHAPTER 6":
                render_with_screenshot_placeholders(doc, combined, FIGURE_MAP)
            else:
                render_chapter_markdown(doc, combined, FIGURE_MAP)

    # Chapter 7 - References
    start_new_section(doc, header_text="IARS \u00b7 Chapter 7", footer_page_fmt="decimal")
    add_chapter_title(doc, "CHAPTER 7", "REFERENCES")
    for i, ref in enumerate(REFERENCES, start=1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Inches(0.4)
        p.paragraph_format.first_line_indent = Inches(-0.4)
        run = p.add_run("[%d] " % i)
        run.bold = True
        p.add_run(ref)

    # Appendices
    start_new_section(doc, header_text="IARS \u00b7 Appendices", footer_page_fmt="decimal")
    doc.add_paragraph("APPENDICES", style="Heading 1")
    appendix_sections = [
        ("Appendix A: Environment Setup and Installation Guide", APPENDIX_A),
        ("Appendix B: Full API Endpoint Reference", APPENDIX_B),
        ("Appendix C: Complete Database Schema Listing", APPENDIX_C),
        ("Appendix D: Sentiment Model and Training Data Details", APPENDIX_D),
        ("Appendix E: Additional UI Screenshots", APPENDIX_E),
        ("Appendix F: Full Test Case Execution Log", APPENDIX_F),
    ]
    for i, (heading, body) in enumerate(appendix_sections):
        doc.add_paragraph(heading, style="Heading 2")
        render_chapter_markdown(doc, body, FIGURE_MAP)
        if i < len(appendix_sections) - 1:
            add_page_break(doc)

    out_path = os.path.join(os.path.dirname(__file__), "IARS-Dissertation.docx")
    doc.save(out_path)
    print("Saved:", out_path)
    print("Paragraphs:", len(doc.paragraphs), "Tables:", len(doc.tables))


if __name__ == "__main__":
    main()
