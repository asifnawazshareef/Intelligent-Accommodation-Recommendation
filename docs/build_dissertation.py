"""
Master assembly script for the IARS dissertation.

Reads:
  - subagent-drafted chapter text files from docs/chapter_drafts/*.txt
    (chapter2.txt, chapter3_design.txt, chapter3_impl.txt, chapter4.txt, chapter6.txt)
  - content_owned.py (Chapter 1, Chapter 5, References, Appendices - authored directly)
  - dissertation_assets/*.png (diagrams generated by generate_diagrams.py)

Produces: docs/IARS-Dissertation.docx
"""
import os
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH

from docx_helpers import (
    new_document, start_new_section, add_page_break, add_chapter_title,
    add_paragraph_text, add_toc_field, render_chapter_markdown,
    add_table_caption_with_tc, add_markdown_table, ASSETS_DIR,
)
from content_owned import (
    CH1_INTRODUCTION, CH5_CONCLUSION, REFERENCES,
    APPENDIX_A, APPENDIX_B, APPENDIX_C, APPENDIX_D, APPENDIX_E, APPENDIX_F,
)

DRAFTS_DIR = os.path.join(os.path.dirname(__file__), "chapter_drafts")

FIGURE_MAP = {}
for fname in os.listdir(ASSETS_DIR):
    if fname.endswith(".png") and not fname.startswith("placeholder_"):
        FIGURE_MAP[fname[:-4]] = os.path.join(ASSETS_DIR, fname)
FIGURE_MAP["SCREENSHOT"] = None  # forces labeled placeholder per-call


def load_draft(name):
    path = os.path.join(DRAFTS_DIR, name)
    if not os.path.exists(path):
        raise FileNotFoundError("Missing chapter draft: %s" % path)
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def render_with_screenshot_placeholders(doc, text, base_figure_map):
    """Chapter 6 uses a shared 'SCREENSHOT' placeholder id per figure; give
    each one a distinct placeholder image keyed by its caption text."""
    lines = text.replace("\r\n", "\n").split("\n")
    pending_caption = None
    local_map = dict(base_figure_map)
    counter = 0
    out_lines = []
    for line in lines:
        if line.strip().upper().startswith("FIGURE_CAPTION:"):
            pending_caption = line.split(":", 1)[1].strip()
            out_lines.append(line)
        elif line.strip().upper().startswith("FIGURE_PLACEHOLDER:") and "SCREENSHOT" in line.upper():
            counter += 1
            key = "SCREENSHOT_%d" % counter
            local_map[key] = None
            out_lines.append("FIGURE_PLACEHOLDER: " + key)
        else:
            out_lines.append(line)
    render_chapter_markdown(doc, "\n".join(out_lines), local_map)


